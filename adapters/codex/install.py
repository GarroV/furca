#!/usr/bin/env python3
"""Install an isolated Codex view of FURCA's authoritative workflows and roles."""
import hashlib
import json
import os
from pathlib import Path
import shlex
import sys
import tempfile

from render import contract, render

ROOT = Path(__file__).resolve().parents[2]
OWNER = "Generated by FURCA Codex adapter"


def digest(text):
    return hashlib.sha256(text.encode()).hexdigest()


def atomic(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as stream:
        stream.write(text)
        tmp = Path(stream.name)
    tmp.replace(path)


def definition(text):
    _, head, body = text.split("---", 2)
    fields = dict(line.split(":", 1) for line in head.splitlines() if ":" in line)
    return {key: value.strip() for key, value in fields.items()}, body.strip()


def hook_groups(data):
    return [(event, group, hook) for event, groups in data.get("hooks", {}).items()
            for group in groups for hook in group.get("hooks", [])
            if "# furca-codex" in hook.get("command", "")]


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        raise ValueError("usage: install.py [--check]")
    home = Path(os.environ.get("CODEX_HOME", str(Path.home() / ".codex"))).expanduser()
    if not home.is_absolute():
        raise ValueError("CODEX_HOME must be absolute")
    home = home.resolve()
    claude = (Path.home() / ".claude").resolve()
    if home == claude or claude in home.parents:
        raise ValueError("CODEX_HOME cannot be the Claude configuration directory")
    own = home / "furca"
    if home not in own.resolve().parents:
        raise ValueError("Codex runtime directory points outside CODEX_HOME")
    bundle = own / "runtime"
    policy_path = own / "models.json"
    for selected in (own / "profile.md", policy_path):
        if selected.resolve() == claude or claude in selected.resolve().parents:
            raise ValueError("Codex profile/policy cannot point into Claude configuration")
    policy_text = (policy_path if policy_path.exists() else ROOT / "adapters/codex/models.json").read_text()
    policy = json.loads(policy_text)
    definitions = sorted((ROOT / "agents").glob("*.md"))
    if set(policy["roles"]) != {p.stem for p in definitions}:
        raise ValueError("model policy must define exactly the canonical roles")
    for setting in list(policy["roles"].values()) + [{"model": policy["session"], "effort": "high"},
                                                   {"model": policy["hard_model"], "effort": "high"}]:
        if not isinstance(setting.get("model"), str) or not setting["model"].strip():
            raise ValueError("missing model id")
        if setting.get("effort") not in ("low", "medium", "high", "xhigh"):
            raise ValueError("invalid reasoning effort")
    profile = own / "profile.md"
    if profile.exists():
        for line in profile.read_text().splitlines():
            if line.startswith("agent_models:") and line.split(":", 1)[1].split("#", 1)[0].strip() not in ("", "{}"):
                raise ValueError("Codex model overrides belong in models.json; agent_models is unsupported")
    outputs, inputs = {}, {}
    layer = contract(home, policy)
    for base in ("skills", "templates", "agents"):
        for source in sorted((ROOT / base).rglob("*")):
            if not source.is_file():
                continue
            rel = source.relative_to(ROOT)
            raw = source.read_text()
            inputs[str(rel)] = digest(raw)
            text = render(raw, home, policy)
            if source.suffix == ".md":
                if raw.startswith("---\n"):
                    _, front, body = text.split("---", 2)
                    text = "---" + front + "---\n<!-- " + OWNER + " -->\n" + layer + body
                else:
                    text = "<!-- " + OWNER + " -->\n" + layer + text
            else:
                if text.startswith("#!"):
                    first, rest = text.split("\n", 1)
                    text = first + "\n# " + OWNER + "\n" + rest
                else:
                    text = "# " + OWNER + "\n" + text
            outputs[bundle / rel] = text
            if base == "skills" and source.name == "SKILL.md":
                outputs[home / "skills" / source.parent.name / "SKILL.md"] = text
    for source in definitions:
        fields, body = definition(source.read_text())
        name = fields["name"]
        settings = policy["roles"][name]
        variants = [(name, settings)]
        if name == "artifex":
            variants.append(("artifex-hard", {"model": policy["hard_model"], "effort": "high"}))
        for native_name, setting in variants:
            values = {"name": native_name, "description": fields["description"],
                      "model": setting["model"], "model_reasoning_effort": setting["effort"],
                      "developer_instructions": layer + render(body, home, policy)}
            outputs[home / "agents" / (native_name + ".toml")] = "# " + OWNER + "\n" + "".join(
                key + " = " + json.dumps(value, ensure_ascii=False) + "\n" for key, value in values.items())
    defaults = (ROOT / "config.defaults.md").read_text()
    inputs["config.defaults.md"] = digest(defaults)
    defaults = defaults.replace("session_model_recommended: opus", "session_model_recommended: " + policy["session"])
    outputs[bundle / "config.defaults.md"] = "<!-- " + OWNER + " -->\n" + render(defaults, home, policy)
    for name in ("continuity.py", "hook.py"):
        original = ROOT / "adapters/codex" / name
        outputs[bundle / "adapters/codex" / name] = (
            "# " + OWNER + "\nimport runpy, sys\n"
            f"sys.path.insert(0, {str(original.parent)!r})\nrunpy.run_path({str(original)!r}, run_name='__main__')\n")
    for base in (ROOT / "hooks", ROOT / "adapters/codex"):
        for source in sorted(base.glob("*.py")):
            inputs[str(source.relative_to(ROOT))] = digest(source.read_text())
    inputs["policy"] = digest(policy_text)
    settings = home / "hooks.json"
    data = json.loads(settings.read_text()) if settings.exists() else {}
    if not isinstance(data, dict) or not isinstance(data.get("hooks", {}), dict):
        raise ValueError("hooks.json must be an object with an object hooks field")
    script = shlex.quote(str(ROOT / "adapters/codex/hook.py"))
    command = (f"[ -f {script} ] || {{ echo 'FURCA Codex hook source missing: reinstall from a stable checkout' >&2; exit 0; }}; "
               + shlex.quote(sys.executable) + " " + script + " # furca-codex")
    required = {}
    for event in ("Stop", "PreToolUse", "SubagentStart", "SubagentStop"):
        group = {"hooks": [{"type": "command", "command": command, "timeout": 20}]}
        if event == "PreToolUse":
            group["matcher"] = "Bash|apply_patch|spawn_agent|Agent|view_image|Read"
        elif event in ("SubagentStart", "SubagentStop"):
            group["matcher"] = "artifex|artifex-hard|optio|norma|exploratio|lector"
        required[event] = group
    stamp = {"source": str(ROOT), "inputs": inputs,
             "outputs": {str(path): digest(text) for path, text in outputs.items()},
             "runtime": "codex", "provider_requested": "openai", "provider_observed": None,
             "live_client_verified": False}
    if check:
        stale = [str(path) for path, text in outputs.items() if not path.is_file() or path.read_text() != text]
        manifest = own / "installation.json"
        if not manifest.exists() or json.loads(manifest.read_text()) != stamp:
            stale.append("source/policy manifest changed")
        registrations = hook_groups(data)
        if len(registrations) != len(required) or {e for e, _, _ in registrations} != set(required):
            stale.append("Codex hook registrations")
        elif any(group != required[event] for event, group, _ in registrations):
            stale.append("Codex hook contract (matcher/type/async/timeout/command)")
        if not profile.exists() or not policy_path.exists():
            stale.append("Codex profile/policy")
        if stale:
            raise ValueError("installation missing or stale: " + ", ".join(stale))
        print("Codex artifacts and hook registrations current; client hook trust/execution still requires a live probe")
        print("Context/usage telemetry unavailable; no Claude runtime state is used")
        return
    if settings.is_symlink():
        raise ValueError("hooks.json is a symlink: configure its canonical source explicitly")
    for path in outputs:
        if path.parent.resolve() != home and home not in path.parent.resolve().parents:
            raise ValueError("installation directory points outside CODEX_HOME: " + str(path.parent))
        if path.is_symlink() or (path.exists() and OWNER not in path.read_text()):
            raise ValueError("unowned installation target: " + str(path))
    for event, groups in list(data.get("hooks", {}).items()):
        kept = []
        for group in groups:
            hooks = [h for h in group.get("hooks", []) if "# furca-codex" not in h.get("command", "")]
            if hooks:
                kept.append(dict(group, hooks=hooks))
        data["hooks"][event] = kept
    for event, group in required.items():
        data.setdefault("hooks", {}).setdefault(event, []).append(group)
    if not profile.exists():
        atomic(profile, f"---\nforge_home: {bundle}\nlanguage: en\nstand_host: \"\"\ntelegram: \"off\"\n"
               + f"session_model_recommended: {policy['session']}\nagent_models: {{}}\n---\n")
    if not policy_path.exists():
        atomic(policy_path, policy_text)
    for path, text in outputs.items():
        atomic(path, text)
        if path.suffix == ".sh":
            path.chmod(0o755)
    atomic(settings, json.dumps(data, ensure_ascii=False, indent=2) + "\n")
    atomic(own / "installation.json", json.dumps(stamp, indent=2) + "\n")
    print("Codex: installed five roles plus artifex-hard, translated workflows and native hooks")
    print("Claude files unchanged. Restart/reload Codex; trust hooks through /hooks and verify a live prohibited action.")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, KeyError, OSError) as error:
        print("FURCA Codex: " + str(error), file=sys.stderr)
        sys.exit(1)
