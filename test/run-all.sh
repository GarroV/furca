#!/usr/bin/env bash
# Прогон всех наборов проверок с честным итогом.
#
# Зачем отдельный скрипт. В README стояла строка
# `for t in test/*.test.sh; do bash "$t"; done` — она печатает всё, но код
# возврата отдаёт от ПОСЛЕДНЕЙ итерации: падение любого набора, кроме
# последнего по алфавиту, оставляло прогон зелёным. Проверка, которая не может
# покраснеть, проверкой не является, а выглядит как она — худший из возможных
# видов (замечено при разборе практик тестирования 19.08.2026, починено
# 17.09.2026).
#
# Итог печатается списком: видно не только «сколько упало», но и что именно, —
# иначе в длинном выводе падение теряется между PASS'ами.

set -uo pipefail

FURCA_HOME="$(cd "$(dirname "$0")/.." && pwd)"
cd "$FURCA_HOME" || exit 1

passed=(); failed=()

for t in test/*.test.sh; do
  [[ -f "$t" ]] || continue
  echo "=== $t"
  if bash "$t"; then
    passed+=("$t")
  else
    failed+=("$t")
  fi
  echo
done

echo "итог: прошло ${#passed[@]}, провалено ${#failed[@]}"
if (( ${#failed[@]} > 0 )); then
  printf '  ПРОВАЛЕНО: %s\n' "${failed[@]}"
  exit 1
fi
echo "PASS"
